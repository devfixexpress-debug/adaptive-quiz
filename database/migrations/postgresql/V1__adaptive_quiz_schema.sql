CREATE INDEX IX_CAT_ITEM_CATALOGO_CATALOGO ON CAT_ITEM_CATALOGO(id_catalogo);
CREATE INDEX IX_CAT_ITEM_CATALOGO_PADRE ON CAT_ITEM_CATALOGO(id_item_padre);

