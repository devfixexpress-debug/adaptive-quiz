CREATE TABLE CAT_CATALOGO (
    id_catalogo BIGINT GENERATED BY DEFAULT AS IDENTITY,
    codigo VARCHAR(50) NOT NULL,
    nombre VARCHAR(120) NOT NULL,
    descripcion VARCHAR(500),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    usuario_creacion VARCHAR(100) NOT NULL DEFAULT 'SYSTEM',
    fecha_modificacion TIMESTAMPTZ,
    usuario_modificacion VARCHAR(100),
    version_registro BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT PK_CAT_CATALOGO PRIMARY KEY (id_catalogo),
    CONSTRAINT UK_CAT_CATALOGO_CODIGO UNIQUE (codigo)
);

CREATE TABLE CAT_ITEM_CATALOGO (
