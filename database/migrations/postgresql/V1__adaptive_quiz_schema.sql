    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    usuario_creacion VARCHAR(100) NOT NULL DEFAULT 'SYSTEM',
    fecha_modificacion TIMESTAMPTZ,
    usuario_modificacion VARCHAR(100),
    version_registro BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT PK_APR_PROGRESO_TEMA PRIMARY KEY (id_progreso_tema),
    CONSTRAINT FK_APR_PROGRESO_TEMA_ESTUDIANTE FOREIGN KEY (id_estudiante)
        REFERENCES APR_ESTUDIANTE(id_estudiante),
    CONSTRAINT FK_APR_PROGRESO_TEMA_TEMA FOREIGN KEY (id_tema)
        REFERENCES ACA_TEMA(id_tema),
