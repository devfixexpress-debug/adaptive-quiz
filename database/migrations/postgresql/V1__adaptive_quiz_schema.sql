CREATE TABLE CFG_REGLA_ADAPTACION (
    id_regla_adaptacion BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_politica_adaptacion BIGINT NOT NULL,
    codigo VARCHAR(60) NOT NULL,
    nombre VARCHAR(150) NOT NULL,
    prioridad INTEGER NOT NULL,
    porcentaje_acierto_min NUMERIC(5,4),
    porcentaje_acierto_max NUMERIC(5,4),
    tiempo_promedio_min_ms INTEGER,
    tiempo_promedio_max_ms INTEGER,
    racha_aciertos_min SMALLINT,
    racha_errores_min SMALLINT,
    id_item_nivel_rendimiento BIGINT NOT NULL,
    id_item_accion_principal BIGINT NOT NULL,
    id_item_tipo_ejercicio_destino BIGINT,
    habilitar_pista BOOLEAN NOT NULL DEFAULT FALSE,
    vigente_desde TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    vigente_hasta TIMESTAMPTZ,
    activa BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    usuario_creacion VARCHAR(100) NOT NULL DEFAULT 'SYSTEM',
    fecha_modificacion TIMESTAMPTZ,
    usuario_modificacion VARCHAR(100),
    version_registro BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT PK_CFG_REGLA_ADAPTACION PRIMARY KEY (id_regla_adaptacion),
    CONSTRAINT FK_CFG_REGLA_ADAPTACION_POLITICA FOREIGN KEY (id_politica_adaptacion)
        REFERENCES CFG_POLITICA_ADAPTACION(id_politica_adaptacion),
    CONSTRAINT FK_CFG_REGLA_ADAPTACION_RENDIMIENTO FOREIGN KEY (id_item_nivel_rendimiento)
        REFERENCES CAT_ITEM_CATALOGO(id_item_catalogo),
    CONSTRAINT FK_CFG_REGLA_ADAPTACION_ACCION FOREIGN KEY (id_item_accion_principal)
        REFERENCES CAT_ITEM_CATALOGO(id_item_catalogo),
    CONSTRAINT FK_CFG_REGLA_ADAPTACION_TIPO_DESTINO FOREIGN KEY (id_item_tipo_ejercicio_destino)
        REFERENCES CAT_ITEM_CATALOGO(id_item_catalogo),
    CONSTRAINT UK_CFG_REGLA_ADAPTACION_CODIGO UNIQUE (id_politica_adaptacion, codigo),
    CONSTRAINT CK_CFG_REGLA_ADAPTACION_PRIORIDAD CHECK (prioridad > 0),
    CONSTRAINT CK_CFG_REGLA_ADAPTACION_ACIERTO_MIN CHECK (porcentaje_acierto_min IS NULL OR porcentaje_acierto_min BETWEEN 0 AND 1),
    CONSTRAINT CK_CFG_REGLA_ADAPTACION_ACIERTO_MAX CHECK (porcentaje_acierto_max IS NULL OR porcentaje_acierto_max BETWEEN 0 AND 1),
    CONSTRAINT CK_CFG_REGLA_ADAPTACION_ACIERTO_RANGO CHECK (
        porcentaje_acierto_min IS NULL OR porcentaje_acierto_max IS NULL OR porcentaje_acierto_max >= porcentaje_acierto_min
    ),
    CONSTRAINT CK_CFG_REGLA_ADAPTACION_TIEMPO CHECK (
        (tiempo_promedio_min_ms IS NULL OR tiempo_promedio_min_ms >= 0)
        AND (tiempo_promedio_max_ms IS NULL OR tiempo_promedio_max_ms >= 0)
        AND (tiempo_promedio_min_ms IS NULL OR tiempo_promedio_max_ms IS NULL OR tiempo_promedio_max_ms >= tiempo_promedio_min_ms)
    ),
    CONSTRAINT CK_CFG_REGLA_ADAPTACION_RACHAS CHECK (
        (racha_aciertos_min IS NULL OR racha_aciertos_min >= 0)
        AND (racha_errores_min IS NULL OR racha_errores_min >= 0)
    ),
    CONSTRAINT CK_CFG_REGLA_ADAPTACION_VIGENCIA CHECK (vigente_hasta IS NULL OR vigente_hasta >= vigente_desde)
);

CREATE INDEX IX_CFG_REGLA_ADAPTACION_POLITICA ON CFG_REGLA_ADAPTACION(id_politica_adaptacion);
CREATE INDEX IX_CFG_REGLA_ADAPTACION_RENDIMIENTO ON CFG_REGLA_ADAPTACION(id_item_nivel_rendimiento);
CREATE INDEX IX_CFG_REGLA_ADAPTACION_ACCION ON CFG_REGLA_ADAPTACION(id_item_accion_principal);

